-- CoastCast v5.0 Launch Backend
-- Supabase/Postgres foundation for real accounts, server-side Premium access,
-- family sharing, complimentary/lifetime grants, admin tools and purchase records.
-- Run after SUPABASE_SETUP.sql. Safe to re-run where noted.

create extension if not exists pgcrypto;

-- ---------- Admins ----------
create table if not exists public.coastcast_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role in ('owner','admin','support')),
  created_at timestamptz not null default now()
);
alter table public.coastcast_admins enable row level security;
drop policy if exists "admin can read own admin row" on public.coastcast_admins;
create policy "admin can read own admin row" on public.coastcast_admins
for select to authenticated using (auth.uid() = user_id);

-- ---------- Direct entitlements ----------
create table if not exists public.coastcast_entitlements (
  user_id uuid primary key references auth.users(id) on delete cascade,
  access_level text not null default 'free' check (access_level in ('free','premium')),
  source text not null default 'free' check (source in ('free','play','complimentary','lifetime','promo','beta')),
  status text not null default 'active' check (status in ('active','grace','expired','revoked')),
  starts_at timestamptz not null default now(),
  expires_at timestamptz,
  granted_by uuid references auth.users(id) on delete set null,
  note text,
  updated_at timestamptz not null default now()
);
alter table public.coastcast_entitlements enable row level security;
drop policy if exists "users can read own entitlement" on public.coastcast_entitlements;
create policy "users can read own entitlement" on public.coastcast_entitlements
for select to authenticated using (auth.uid() = user_id);

-- ---------- Family membership ----------
create table if not exists public.coastcast_family_members (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  member_user_id uuid references auth.users(id) on delete cascade,
  invite_email text,
  status text not null default 'invited' check (status in ('invited','active','removed','expired')),
  created_at timestamptz not null default now(),
  joined_at timestamptz,
  removed_at timestamptz,
  unique(owner_id, member_user_id)
);
create unique index if not exists coastcast_family_pending_unique
on public.coastcast_family_members(owner_id, lower(invite_email))
where member_user_id is null and status='invited';
create unique index if not exists coastcast_family_one_active_membership
on public.coastcast_family_members(member_user_id)
where member_user_id is not null and status='active';

alter table public.coastcast_family_members enable row level security;
drop policy if exists "family users can read membership" on public.coastcast_family_members;
create policy "family users can read membership" on public.coastcast_family_members
for select to authenticated using (auth.uid() = owner_id or auth.uid() = member_user_id);

-- ---------- Audit trail ----------
create table if not exists public.coastcast_entitlement_audit (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  access_level text,
  source text,
  expires_at timestamptz,
  actor_id uuid references auth.users(id) on delete set null,
  note text,
  created_at timestamptz not null default now()
);
alter table public.coastcast_entitlement_audit enable row level security;
drop policy if exists "users can read own entitlement audit" on public.coastcast_entitlement_audit;
create policy "users can read own entitlement audit" on public.coastcast_entitlement_audit
for select to authenticated using (auth.uid() = user_id);

